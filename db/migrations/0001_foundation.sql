-- 0001 Foundation: schema, roles, market data, investor data, model and run logs.
--
-- Access model (docs/DECISIONS.md, "B2 Database"):
--   * Everything lives in schema `finn`, which Supabase's Data API does not expose, and the
--     Supabase API roles (anon, authenticated, service_role) are given nothing in it. The
--     publishable and secret keys therefore cannot reach these tables through the REST API.
--   * The pipeline and the API connect with the database URL and immediately drop to a
--     least-privilege role for their work: finn_ingest (writes public market data) or
--     finn_api (reads market data; reads and writes one investor's rows at a time).
--   * Row-level security is enabled on every table. Investor rows are visible only when the
--     request has set `finn.investor_id` to that investor: the API scopes every investor
--     query, and the database refuses the rest even if the API forgets.

set search_path = finn, extensions, public;

create schema if not exists finn;
create schema if not exists extensions;
create extension if not exists vector with schema extensions;

do $$
begin
  if not exists (select from pg_roles where rolname = 'finn_ingest') then
    create role finn_ingest nologin;
  end if;
  if not exists (select from pg_roles where rolname = 'finn_api') then
    create role finn_api nologin;
  end if;
end
$$;
-- On Postgres 16+, creating a role does not let its creator switch into it; this grant does.
grant finn_ingest, finn_api to current_user;

revoke all on schema finn from public;
grant usage on schema finn to finn_ingest, finn_api;
-- pgvector lives in `extensions`. Grant its use if this admin may; otherwise stop here, because
-- roles that cannot use the vector type would fail later, at the first embedding.
do $$
begin
  if has_schema_privilege('extensions', 'USAGE WITH GRANT OPTION') then
    grant usage on schema extensions to finn_ingest, finn_api;
  elsif not (has_schema_privilege('finn_api', 'extensions', 'USAGE')
             and has_schema_privilege('finn_ingest', 'extensions', 'USAGE')) then
    raise exception 'finn_ingest and finn_api need USAGE on schema extensions (pgvector), and % cannot grant it',
      current_user;
  end if;
end
$$;

-- Market data: public, the same for every investor ---------------------------------------------

create table finn.companies (
  symbol      text primary key check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  name        text,
  isin        text check (isin is null or isin ~ '^IN[A-Z0-9]{10}$'),
  industry    text,
  updated_at  timestamptz not null default now()
);

-- One row per exchange filing, keyed by NSE's own id. The classification columns are recomputed
-- whenever the rules change; rule_version records which rules produced them.
create table finn.filings (
  seq_id              text primary key check (seq_id ~ '^[0-9A-Za-z_-]{1,40}$'),
  symbol              text not null check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  company             text not null,
  ts                  timestamptz not null,
  source              text not null default 'NSE' check (source in ('NSE', 'BSE')),
  label               text not null default '',
  subject             text not null default '',
  url                 text not null default '' check (url = '' or url ~ '^https://'),
  file_size           text not null default '',
  category            text,
  subtype             text,
  role                text,
  action              text,
  detail_in_document  boolean,
  needs_model         boolean,
  rule_id             text,
  rule_version        text,
  summary             text,  -- one-line "what changed" from the filing reader (task C3)
  summary_quote       text,  -- the sentence of the filing that summary rests on
  fetched_at          timestamptz not null default now()
);
create index filings_symbol_ts on finn.filings (symbol, ts desc);
create index filings_ts on finn.filings (ts desc);

-- Quarterly results parsed from XBRL: the latest revision per quarter and basis. Figures are in
-- ₹ crore, keyed by metric, exactly as parsed; nothing here is ever generated by a model.
create table finn.results (
  symbol        text not null check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  quarter_end   date not null,
  consolidated  boolean not null,
  template      text not null check (template in ('general', 'bank', 'lender')),
  period_start  date not null,
  period_end    date not null,
  audited       text not null default '',
  revision      boolean not null default false,
  broadcast     timestamptz not null,
  xbrl_url      text not null check (xbrl_url ~ '^https://'),
  figures       jsonb not null check (jsonb_typeof(figures) = 'object'),
  parsed_at     timestamptz not null default now(),
  primary key (symbol, quarter_end, consolidated),
  -- the year-to-date guard: a quarter is 80-95 days, never the half-year or nine months
  check (period_end - period_start between 80 and 95)
);

create table finn.prices_eod (
  symbol      text not null check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  day         date not null,
  series      text not null default 'EQ',
  close       numeric(14, 4) not null check (close > 0),
  prev_close  numeric(14, 4) check (prev_close > 0),
  volume      bigint not null check (volume >= 0),
  turnover    numeric(20, 2) check (turnover >= 0),
  primary key (symbol, day)
);
create index prices_eod_day on finn.prices_eod (day);

-- The exchange's own calendar: a day is a session if NSE published a bhavcopy for it.
create table finn.trading_days (
  day         date primary key,
  is_session  boolean not null,
  checked_at  timestamptz not null default now()
);

-- NSE's pledge feed names the company but carries no symbol; symbol is resolved at ingest.
create table finn.pledges (
  company_name                   text not null,
  as_of                          date not null,
  broadcast                      timestamptz not null,
  symbol                         text check (symbol is null or symbol ~ '^[A-Z0-9&-]{1,20}$'),
  promoter_holding_pct           numeric(7, 2) check (promoter_holding_pct between 0 and 100),
  pledged_of_promoter_pct        numeric(7, 2) check (pledged_of_promoter_pct between 0 and 100),
  promoter_pledged_of_total_pct  numeric(7, 2) check (promoter_pledged_of_total_pct between 0 and 100),
  all_pledged_of_demat_pct       numeric(7, 2) check (all_pledged_of_demat_pct between 0 and 100),
  promoter_shares                bigint check (promoter_shares >= 0),
  promoter_pledged_shares        bigint check (promoter_pledged_shares >= 0),
  issued_shares                  bigint check (issued_shares >= 0),
  fetched_at                     timestamptz not null default now(),
  primary key (company_name, as_of, broadcast)
);
create index pledges_symbol on finn.pledges (symbol, broadcast desc);

create table finn.board_meetings (
  symbol       text not null check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  day          date not null,
  purpose      text not null,
  description  text not null default '',
  announced    timestamptz,
  primary key (symbol, day, purpose)
);
create index board_meetings_day on finn.board_meetings (day);

-- Ex-dates matter to price alerts: a bonus or split day is not an unusual move.
create table finn.corporate_actions (
  symbol   text not null check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  ex_date  date not null,
  subject  text not null,
  primary key (symbol, ex_date, subject)
);

-- Primary-source documents for Pull, and their page-anchored chunks with embeddings.
create table finn.documents (
  id          bigint generated always as identity primary key,
  symbol      text not null check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  kind        text not null check (kind in ('annual_report', 'transcript', 'presentation', 'filing')),
  title       text not null default '',
  period      text,
  published   date,
  url         text not null unique check (url ~ '^https://'),
  sha256      text check (sha256 is null or sha256 ~ '^[0-9a-f]{64}$'),
  pages       integer check (pages >= 0),
  fetched_at  timestamptz not null default now()
);
create index documents_symbol on finn.documents (symbol, kind, published desc);

-- 768 dimensions = GEMINI_EMBED_DIM. Changing the embedding size is a new migration, not a setting.
create table finn.chunks (
  id           bigint generated always as identity primary key,
  document_id  bigint not null references finn.documents (id) on delete cascade,
  page         integer not null check (page >= 1),
  ord          integer not null check (ord >= 0),
  text         text not null check (length(text) between 1 and 20000),
  embedding    vector(768),
  unique (document_id, ord)
);
create index chunks_embedding on finn.chunks using hnsw (embedding vector_cosine_ops);

-- Investor data: private, one investor at a time ------------------------------------------------

create table finn.investors (
  id               uuid primary key default gen_random_uuid(),
  display_name     text not null check (length(display_name) between 1 and 80),
  is_demo          boolean not null default false,
  network_enabled  boolean not null default false,
  created_at       timestamptz not null default now()
);

create table finn.holdings (
  investor_id  uuid not null references finn.investors (id) on delete cascade,
  symbol       text not null check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  thesis       text not null default '' check (length(thesis) <= 600),
  added_on     date not null default current_date,
  primary key (investor_id, symbol)
);

-- Defaults match finn.alerts.Thresholds and finn.rank.Prefs (a test keeps them in step).
create table finn.prefs (
  investor_id       uuid primary key references finn.investors (id) on delete cascade,
  window_hours      integer not null default 24 check (window_hours between 1 and 744),
  volume_multiple   numeric(4, 2) not null default 2.0 check (volume_multiple between 1.1 and 10),
  move_pct          numeric(5, 2) not null default 5.0 check (move_pct between 0.5 and 30),
  move_sigma        numeric(4, 2) not null default 3.0 check (move_sigma between 1 and 10),
  move_rule         text not null default 'either' check (move_rule in ('pct', 'sigma', 'either')),
  alert_categories  text[] not null default '{results,M&A,management_change,litigation,pledging}',
  last_seen_at      timestamptz
);

-- Decision notes and feedback: kept as future training data for ENAM's Wave 1 ("learning loop").
create table finn.notes (
  id             bigint generated always as identity primary key,
  investor_id    uuid not null references finn.investors (id) on delete cascade,
  symbol         text not null check (symbol ~ '^[A-Z0-9&-]{1,20}$'),
  filing_seq_id  text,
  kind           text not null check (kind in ('decision', 'feedback')),
  body           text not null check (length(body) between 1 and 2000),
  created_at     timestamptz not null default now()
);
create index notes_investor on finn.notes (investor_id, symbol, created_at desc);

-- Model calls and runs -------------------------------------------------------------------------

create table finn.llm_calls (
  id              bigint generated always as identity primary key,
  at              timestamptz not null default now(),
  role            text not null,
  model           text not null,
  prompt_version  text not null,
  input_hash      text not null check (input_hash ~ '^[0-9a-f]{64}$'),
  input_tokens    integer check (input_tokens >= 0),
  output_tokens   integer check (output_tokens >= 0),
  latency_ms      integer check (latency_ms >= 0),
  cache_hit       boolean not null default false,
  fallback_from   text,
  ok              boolean not null,
  error           text
);
create index llm_calls_at on finn.llm_calls (at desc);

create table finn.llm_cache (
  input_hash      text primary key check (input_hash ~ '^[0-9a-f]{64}$'),
  role            text not null,
  model           text not null,
  prompt_version  text not null,
  output          jsonb not null,
  created_at      timestamptz not null default now()
);

create table finn.ingest_runs (
  id           bigint generated always as identity primary key,
  job          text not null,
  started_at   timestamptz not null default now(),
  finished_at  timestamptz,
  ok           boolean,
  counts       jsonb not null default '{}',
  error        text
);
create index ingest_runs_job on finn.ingest_runs (job, started_at desc);

-- Who reads the investor scope -----------------------------------------------------------------

create function finn.current_investor() returns uuid
language sql stable
as $$ select nullif(current_setting('finn.investor_id', true), '')::uuid $$;

-- Privileges -------------------------------------------------------------------------------------

revoke all on all tables in schema finn from public;
revoke all on all sequences in schema finn from public;
revoke all on function finn.current_investor() from public;

-- Supabase's API roles get nothing here (they exist only on Supabase, not in a plain Postgres).
do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated', 'service_role'] loop
    if exists (select from pg_roles where rolname = r) then
      execute format('revoke all on schema finn from %I', r);
      execute format('revoke all on all tables in schema finn from %I', r);
      execute format('revoke all on all sequences in schema finn from %I', r);
      execute format('revoke all on all functions in schema finn from %I', r);
    end if;
  end loop;
end
$$;

-- finn_ingest: writes public market data, never sees investor data.
grant select, insert, update, delete on
  finn.companies, finn.filings, finn.results, finn.prices_eod, finn.trading_days, finn.pledges,
  finn.board_meetings, finn.corporate_actions, finn.documents, finn.chunks, finn.llm_cache,
  finn.ingest_runs
  to finn_ingest;
grant select, insert on finn.llm_calls to finn_ingest;

-- finn_api: reads market data; writes documents, chunks and the model cache (Pull on a company
-- not yet ingested); reads and writes investor rows under row-level security.
grant select on
  finn.companies, finn.filings, finn.results, finn.prices_eod, finn.trading_days, finn.pledges,
  finn.board_meetings, finn.corporate_actions, finn.ingest_runs
  to finn_api;
grant select, insert, update on finn.documents, finn.chunks, finn.llm_cache to finn_api;
grant select, insert on finn.llm_calls to finn_api;
grant select on finn.investors to finn_api;
grant select, insert, update, delete on finn.holdings, finn.prefs, finn.notes to finn_api;
grant execute on function finn.current_investor() to finn_api;

grant usage on all sequences in schema finn to finn_ingest, finn_api;

-- Row-level security -----------------------------------------------------------------------------

do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'finn' loop
    execute format('alter table finn.%I enable row level security', t);
  end loop;
end
$$;

-- Market tables: whatever the role was granted, for every row.
do $$
declare t text;
begin
  foreach t in array array['companies', 'filings', 'results', 'prices_eod', 'trading_days', 'pledges',
                           'board_meetings', 'corporate_actions', 'documents', 'chunks', 'llm_cache',
                           'llm_calls', 'ingest_runs'] loop
    execute format('create policy ingest_rows on finn.%I for all to finn_ingest using (true) with check (true)', t);
    execute format('create policy api_rows on finn.%I for all to finn_api using (true) with check (true)', t);
  end loop;
end
$$;

-- Investor tables: only the investor the request is scoped to.
create policy own_row on finn.investors for select to finn_api
  using (id = finn.current_investor());
create policy own_rows on finn.holdings for all to finn_api
  using (investor_id = finn.current_investor()) with check (investor_id = finn.current_investor());
create policy own_rows on finn.prefs for all to finn_api
  using (investor_id = finn.current_investor()) with check (investor_id = finn.current_investor());
create policy own_rows on finn.notes for all to finn_api
  using (investor_id = finn.current_investor()) with check (investor_id = finn.current_investor());
